"use client";

import { Table, TableBody, TableCell, TableColumn, TableHeader, TableRow } from "@heroui/react";
import type { BuilderDependenciesManifest } from "@/lib/deps-manifest";

export function DependenciesTable({ manifest }: { manifest: BuilderDependenciesManifest }) {
  const rows = Object.entries(manifest.groups).flatMap(([group, deps]) =>
    deps.map((dep) => ({ group, ...dep }))
  );

  return (
    <div className="flex flex-col gap-2">
      <p className="text-small text-default-500">
        Read-only. Generated by `bun run deps:manifest`
        {manifest.generatedAt ? ` on ${new Date(manifest.generatedAt).toLocaleString()}` : ""}.
      </p>
      <Table aria-label="Builder dependencies" removeWrapper>
        <TableHeader>
          <TableColumn>GROUP</TableColumn>
          <TableColumn>PACKAGE</TableColumn>
          <TableColumn>VERSION</TableColumn>
          <TableColumn>PURPOSE</TableColumn>
        </TableHeader>
        <TableBody items={rows} emptyContent="No dependencies recorded yet.">
          {(row) => (
            <TableRow key={`${row.group}-${row.name}`}>
              <TableCell className="capitalize text-default-500">{row.group}</TableCell>
              <TableCell className="font-mono text-small">{row.name}</TableCell>
              <TableCell className="font-mono text-small">{row.version}</TableCell>
              <TableCell>{row.purpose}</TableCell>
            </TableRow>
          )}
        </TableBody>
      </Table>
    </div>
  );
}
