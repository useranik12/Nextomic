"use client";

import { Table } from "@heroui/react";
import type { BuilderDependenciesManifest } from "@/lib/deps-manifest";

export function DependenciesTable({ manifest }: { manifest: BuilderDependenciesManifest }) {
  const rows = Object.entries(manifest.groups).flatMap(([group, deps]) =>
    deps.map((dep) => ({ group, ...dep }))
  );

  return (
    <div className="flex flex-col gap-2">
      <p className="text-sm text-muted">
        Read-only. Generated by `bun run deps:manifest`
        {manifest.generatedAt ? ` on ${new Date(manifest.generatedAt).toLocaleString()}` : ""}.
      </p>
      <Table>
        <Table.ScrollContainer>
          <Table.Content aria-label="Builder dependencies">
            <Table.Header>
              <Table.Column id="group" isRowHeader>
                Group
              </Table.Column>
              <Table.Column id="name">Package</Table.Column>
              <Table.Column id="version">Version</Table.Column>
              <Table.Column id="purpose">Purpose</Table.Column>
            </Table.Header>
            <Table.Body
              items={rows.map((row) => ({ ...row, id: `${row.group}-${row.name}` }))}
              renderEmptyState={() => (
                <p className="p-4 text-sm text-muted">No dependencies recorded yet.</p>
              )}
            >
              {(row) => (
                <Table.Row id={row.id}>
                  <Table.Cell className="capitalize text-muted">{row.group}</Table.Cell>
                  <Table.Cell className="font-mono text-sm">{row.name}</Table.Cell>
                  <Table.Cell className="font-mono text-sm">{row.version}</Table.Cell>
                  <Table.Cell>{row.purpose}</Table.Cell>
                </Table.Row>
              )}
            </Table.Body>
          </Table.Content>
        </Table.ScrollContainer>
      </Table>
    </div>
  );
}
