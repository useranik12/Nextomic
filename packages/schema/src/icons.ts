import { z } from "zod";

// Icon libraries for built sites (docs/fonts-and-icons.md section 3). Every installed library is
// stored per project as one JSON file in storage; pages refer to icons as { library, name }, never
// as raw SVG, so a library update or removal applies on the next build.

/** A library key is also the CSS prefix of its icons. */
export const ICON_KEY_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;
/** Iconify icon names are lowercase words joined by hyphens. */
export const ICON_NAME_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;

export const ICON_SOURCES = [
  "iconify",
  "iconify-json",
  "upload-svg",
  "icomoon",
  "fontello",
  "upload-font"
] as const;
export type IconSource = (typeof ICON_SOURCES)[number];

/** `svg`: inline SVG (default, multicolor and animated icons work). `font`: glyph font files. */
export const ICON_MODES = ["svg", "font"] as const;

export const iconKeySchema = z.string().regex(ICON_KEY_PATTERN).max(40);
export const iconNameSchema = z.string().regex(ICON_NAME_PATTERN).max(120);

/** How an icon is stored in page JSON. */
export const iconRefSchema = z.object({ library: iconKeySchema, name: iconNameSchema });
export type IconRef = z.infer<typeof iconRefSchema>;

export const iconLibrarySchema = z.object({
  key: iconKeySchema,
  name: z.string().trim().min(1).max(80),
  source: z.enum(ICON_SOURCES),
  /** The package version the data was taken from; "Update" compares it with the newest one. */
  version: z.string().max(40).default(""),
  author: z.string().max(120).default(""),
  license: z.string().max(80).default(""),
  licenseUrl: z.string().max(300).default(""),
  /** CC BY style licenses: a notice shows in the UI and the export carries a credits file. */
  requiresAttribution: z.boolean().default(false),
  /** Brand and product marks: the files are free to use, the trademarks are not. */
  brand: z.boolean().default(false),
  mode: z.enum(ICON_MODES).default("svg"),
  /** Icons keep their own colors (emoji, logos, multicolor sets). */
  palette: z.boolean().default(false),
  /** Contains SMIL animated icons. */
  animated: z.boolean().default(false),
  count: z.number().int().min(0).max(100_000),
  bytes: z.number().int().min(0).max(100_000_000),
  sha256: z.string().regex(/^[0-9a-f]{64}$/),
  /** Hidden from the picker while off; icons already in use keep rendering. */
  enabled: z.boolean().default(true),
  installedAt: z.string().max(40).default("")
});
export type IconLibrary = z.infer<typeof iconLibrarySchema>;

export const iconLibraryListSchema = z
  .array(iconLibrarySchema)
  .max(80)
  .refine((list) => new Set(list.map((l) => l.key)).size === list.length, {
    message: "Icon library keys must be unique."
  });

/** One row of the built-in catalog (generated by scripts/gen-icon-catalog.mjs). */
export interface IconCatalogEntry {
  prefix: string;
  name: string;
  author: string;
  authorUrl: string;
  license: string;
  licenseSpdx: string;
  licenseUrl: string;
  total: number;
  category: string;
  palette: boolean;
  animated: boolean;
  brand: boolean;
  requiresAttribution: boolean;
  samples: { name: string; body: string; width: number; height: number }[];
}

// ------------------------------------------------------------------ Iconify set data

export const ICONIFY_MAX_ICONS = 60_000;
export const ICONIFY_MAX_BYTES = 60_000_000;

const iconDataSchema = z
  .object({
    body: z.string().max(200_000),
    left: z.number().optional(),
    top: z.number().optional(),
    width: z.number().positive().max(10_000).optional(),
    height: z.number().positive().max(10_000).optional(),
    rotate: z.number().optional(),
    hFlip: z.boolean().optional(),
    vFlip: z.boolean().optional()
  })
  .passthrough();

const aliasSchema = z
  .object({
    parent: z.string().max(200),
    left: z.number().optional(),
    top: z.number().optional(),
    width: z.number().positive().max(10_000).optional(),
    height: z.number().positive().max(10_000).optional(),
    rotate: z.number().optional(),
    hFlip: z.boolean().optional(),
    vFlip: z.boolean().optional()
  })
  .passthrough();

/** An Iconify icon set (`icons.json` of an `@iconify-json/<prefix>` package). */
export const iconifySetSchema = z
  .object({
    prefix: z.string().max(80),
    lastModified: z.number().optional(),
    icons: z.record(z.string().max(200), iconDataSchema),
    aliases: z.record(z.string().max(200), aliasSchema).optional(),
    width: z.number().positive().max(10_000).optional(),
    height: z.number().positive().max(10_000).optional()
  })
  .passthrough()
  .refine((set) => Object.keys(set.icons).length <= ICONIFY_MAX_ICONS, {
    message: "This icon set has too many icons."
  });
export type IconifySet = z.infer<typeof iconifySetSchema>;

/** Every name an icon set offers: its icons and its aliases. */
export const iconifyNames = (set: Pick<IconifySet, "icons" | "aliases">): string[] =>
  [...Object.keys(set.icons), ...Object.keys(set.aliases ?? {})].sort();
