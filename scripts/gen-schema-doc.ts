import { writeFileSync } from "node:fs";
import { zodToJsonSchema } from "zod-to-json-schema";
import {
  breakpointListSchema,
  createPageInputSchema,
  elementNodeSchema,
  pageSettingsSchema,
  projectSettingsSchema,
  savePageInputSchema,
  styleMapSchema
} from "../packages/schema/src";

// Generates docs/schema.md from the Zod schemas (packages/schema is the source of truth).
const entries = [
  ["ElementNode", elementNodeSchema],
  ["StyleMap", styleMapSchema],
  ["BreakpointList", breakpointListSchema],
  ["ProjectSettings", projectSettingsSchema],
  ["PageSettings", pageSettingsSchema],
  ["CreatePageInput", createPageInputSchema],
  ["SavePageInput", savePageInputSchema]
] as const;

const parts = [
  "# Schema reference",
  "",
  "Generated by `bun run schema:doc` from `packages/schema`. Do not edit by hand.",
  ""
];
for (const [name, schema] of entries) {
  const json = zodToJsonSchema(schema, { name, $refStrategy: "root" });
  parts.push(`## ${name}`, "", "```json", JSON.stringify(json, null, 2), "```", "");
}
writeFileSync(new URL("../docs/schema.md", import.meta.url), parts.join("\n"));
process.stdout.write(`${`Wrote docs/schema.md (${entries.length} schemas)`}
`);
